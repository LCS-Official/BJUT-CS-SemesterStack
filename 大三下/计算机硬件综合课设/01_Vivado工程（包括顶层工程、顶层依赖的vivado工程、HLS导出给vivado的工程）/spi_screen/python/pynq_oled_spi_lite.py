class OledSpiLite:
    def __init__(self, ip, width=128, height=64, controller="ssd1309", clk_div=5):
        self.ip = ip
        self.width = int(width)
        self.height = int(height)
        self.pages = self.height // 8
        self.controller = str(controller).lower()
        self.col_offset = 2 if self.controller == "sh1106" else 0
        self.buf = bytearray(self.width * self.pages)
        self.dc = 0
        self.cs_n = 1
        self.res_n = 1
        self.ip.write(CLKDIV, max(2, int(clk_div)))
        self._write_ctrl()

    def _ctrl_word(self, start=0):
        return (
            (CTRL_START if start else 0)
            | (CTRL_DC if self.dc else 0)
            | (CTRL_CS_N if self.cs_n else 0)
            | (CTRL_RES_N if self.res_n else 0)
        )

    def _write_ctrl(self, start=0):
        self.ip.write(CTRL, self._ctrl_word(start=start))

    def wait_idle(self, timeout=0.05):
        t0 = time.perf_counter()
        while self.ip.read(STATUS) & 0x1:
            if time.perf_counter() - t0 > timeout:
                raise TimeoutError("oled_spi_lite busy timeout")

    def set_pins(self, dc=None, cs_n=None, res_n=None):
        if dc is not None:
            self.dc = 1 if dc else 0
        if cs_n is not None:
            self.cs_n = 1 if cs_n else 0
        if res_n is not None:
            self.res_n = 1 if res_n else 0
        self._write_ctrl()

    def write_byte(self, value, dc):
        self.wait_idle()
        self.dc = 1 if dc else 0
        self.cs_n = 0
        self.ip.write(TXDATA, int(value) & 0xFF)
        self._write_ctrl(start=1)
        self.wait_idle()

    def command(self, value):
        self.write_byte(value, dc=0)

    def commands(self, values):
        for value in values:
            self.command(value)

    def data(self, values):
        for value in values:
            self.write_byte(value, dc=1)

    def deselect(self):
        self.set_pins(cs_n=1)

    def hardware_reset(self):
        self.set_pins(res_n=1, cs_n=1, dc=0)
        time.sleep(0.02)
        self.set_pins(res_n=0)
        time.sleep(0.05)
        self.set_pins(res_n=1)
        time.sleep(0.05)

    def init_display(self):
        self.hardware_reset()
        if self.controller == "sh1106":
            init = [
                0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
                0xAD, 0x8B, 0xA1, 0xC8, 0xDA, 0x12, 0x81, 0x7F,
                0xD9, 0x1F, 0xDB, 0x40, 0xA4, 0xA6, 0xAF,
            ]
        else:
            init = [
                0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
                0x8D, 0x14, 0x20, 0x00, 0xA1, 0xC8, 0xDA, 0x12,
                0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF,
            ]
        self.commands(init)
        self.clear()
        self.flush()
        self.deselect()

    def clear(self, value=0x00):
        self.buf[:] = bytes([int(value) & 0xFF]) * len(self.buf)

    def pixel(self, x, y, on=True):
        x = int(x)
        y = int(y)
        if x < 0 or x >= self.width or y < 0 or y >= self.height:
            return
        idx = (y // 8) * self.width + x
        mask = 1 << (y & 7)
        if on:
            self.buf[idx] |= mask
        else:
            self.buf[idx] &= (~mask) & 0xFF

    def text(self, x, y, msg):
        page = max(0, min(self.pages - 1, int(y) // 8))
        col = int(x)
        for ch in str(msg).upper():
            glyph = FONT5X7.get(ch, FONT5X7[" "])
            if col + 5 >= self.width:
                break
            base = page * self.width + col
            for i, bits in enumerate(glyph):
                if 0 <= col + i < self.width:
                    self.buf[base + i] = bits
            if col + 5 < self.width:
                self.buf[base + 5] = 0
            col += 6

    def ascii5(self, x, y, ch):
        glyph = FONT5X7.get(str(ch).upper(), FONT5X7[" "])
        x = int(x)
        y = int(y)
        for xx, bits in enumerate(glyph):
            for yy in range(7):
                if bits & (1 << yy):
                    self.pixel(x + xx, y + yy, True)

    def zh12(self, x, y, ch):
        rows = ZH12.get(ch)
        if rows is None:
            return
        x = int(x)
        y = int(y)
        for yy, row in enumerate(rows):
            for xx in range(12):
                if row & (1 << (11 - xx)):
                    self.pixel(x + xx, y + yy, True)

    def text_mixed(self, x, y, msg):
        col = int(x)
        y = int(y)
        for ch in str(msg):
            if ch in ZH12:
                if col + 12 > self.width:
                    break
                self.zh12(col, y, ch)
                col += 13
            else:
                if col + 5 > self.width:
                    break
                self.ascii5(col, y + 3, ch)
                col += 6 if ch != " " else 4

    def hbar(self, x, y, w, ratio, h=6):
        ratio = max(0.0, min(1.0, float(ratio)))
        filled = int(max(0, int(w)) * ratio)
        for xx in range(int(w)):
            for yy in range(int(h)):
                self.pixel(int(x) + xx, int(y) + yy, xx < filled)

    def rect(self, x, y, w, h):
        x = int(x)
        y = int(y)
        w = max(1, int(w))
        h = max(1, int(h))
        for xx in range(w):
            self.pixel(x + xx, y, True)
            self.pixel(x + xx, y + h - 1, True)
        for yy in range(h):
            self.pixel(x, y + yy, True)
            self.pixel(x + w - 1, y + yy, True)

    def flush(self):
        if self.controller == "sh1106":
            for page in range(self.pages):
                col = self.col_offset
                self.commands([0xB0 + page, 0x00 | (col & 0x0F), 0x10 | (col >> 4)])
                start = page * self.width
                self.data(self.buf[start:start + self.width])
        else:
            self.commands([0x21, 0x00, self.width - 1, 0x22, 0x00, self.pages - 1])
            self.data(self.buf)
        self.deselect()

    def show_status(self, frame=0, fps=0.0, alert=False, score=0, ratio=0.0,
                    pred=-1, roi=0, eye=0, svm=0):
        score_i = int(score)
        score_disp = "NA" if score_i == -2147483648 else str(int(score_i / 1000))
        pred_i = int(pred)
        if pred_i == 1:
            pred_disp = "闭眼"
        elif pred_i == 0:
            pred_disp = "睁眼"
        else:
            pred_disp = "--"

        self.clear()
        self.text_mixed(0, 0, "状态:" + ("警报" if alert else "正常"))
        self.text_mixed(0, 12, f"帧率:{float(fps):4.1f} 帧数:{int(frame)}")
        self.text_mixed(0, 24, f"SVM分数:{score_disp} 判:{pred_disp}")
        self.text_mixed(0, 36, f"比例:{int(float(ratio) * 100):3d}%")
        self.text_mixed(0, 48, f"脸:{int(roi)} 眼:{int(eye)} SVM:{int(svm)}")
        self.hbar(0, 61, self.width, ratio, h=3)
        self.flush()

    def show_standby(self, countdown=5, no_face_sec=0.0):
        countdown = max(0, int(countdown))
        self.clear()
        self.rect(0, 0, self.width, self.height)
        self.text_mixed(35, 4, "待机模式")
        self.text_mixed(25, 18, "未检测到人脸")
        self.text_mixed(31, 34, f"{countdown}秒后检测")
        self.text_mixed(25, 48, "用户返回检测")
        # A small animated-looking dotted footer; the countdown changes which dots are lit.
        phase = countdown % 5
        for i in range(10):
            if (i + phase) % 3 != 0:
                self.pixel(16 + i * 10, 60, True)
                self.pixel(17 + i * 10, 60, True)
        self.flush()


def get_ip(overlay, name="oled_spi_lite_0"):
    if hasattr(overlay, name):
        return getattr(overlay, name)
    keys = list(getattr(overlay, "ip_dict", {}).keys())
    lower = {k.lower(): k for k in keys}
    if name.lower() in lower and hasattr(overlay, lower[name.lower()]):
        return getattr(overlay, lower[name.lower()])
    raise RuntimeError(f"IP {name!r} not found. Available: {keys}")


